/**
 * Alert lifecycle / case management:
 * <pre>
 *   OPEN ─assign─▶ IN_REVIEW ─▶ ESCALATED ─▶ CLOSED_SAR_FILED   (via fileSar)
 *     └──────────────┴────────────┴────────▶ CLOSED_FALSE_POSITIVE
 * </pre>
 * Every change is written to the alert's note trail. Closed alerts are immutable.
 */
@Service
public class AlertService {

    public static final String SYSTEM = "system";

    private final AlertRepository alerts;
    private final AlertNoteRepository notes;
    private final SarReportRepository sars;
    private final CustomerRiskService risk;
    private final ApplicationEventPublisher events;

    public AlertService(AlertRepository alerts, AlertNoteRepository notes, SarReportRepository sars,
                        CustomerRiskService risk, ApplicationEventPublisher events) {
        this.alerts = alerts;
        this.notes = notes;
        this.sars = sars;
        this.risk = risk;
        this.events = events;
    }

    // ---------------------------------------------------------------- creation

    @Transactional
    public Alert createTransactionAlert(Transaction tx, List<RuleHit> hits, int score) {
        Alert alert = new Alert();
        alert.setAlertNumber(Ids.next("ALT"));
        alert.setType(AlertType.TRANSACTION);
        alert.setTransaction(tx);
        alert.setCustomer(tx.getAccount().getCustomer());
        alert.setScore(score);
        alert.setSeverity(tx.getStatus() == TransactionStatus.BLOCKED && score < 80 ? Severity.HIGH
                : Severity.fromScore(score));
        alert.setHits(hits);
        int more = hits.size() - 1;
        alert.setSummary(hits.get(0).getRuleName()
                + (more == 0 ? "" : " and " + more + " more finding" + (more == 1 ? "" : "s")));
        // Monitoring is real-time, so the alert is as old as the transaction that raised it.
        Instant ts = tx.getTimestamp();
        alert.setCreatedAt(ts.isBefore(Instant.now()) ? ts : Instant.now());
        alerts.save(alert);
        notes.save(new AlertNote(alert, SYSTEM, "Alert generated by transaction monitoring. Transaction "
                + tx.getStatus().name().toLowerCase() + " with risk score " + score + ".", true));
        boolean held = tx.getStatus() == TransactionStatus.BLOCKED;
        if (held || alert.getSeverity() == Severity.CRITICAL) {
            events.publishEvent(new UrgentAlertRaised(alert.getId(), alert.getAlertNumber(),
                    alert.getCustomer().getFullName(), alert.getSummary(), alert.getSeverity(), held));
        }
        return alert;
    }

    @Transactional
    public Alert createScreeningAlert(Customer customer, ScreeningMatchDto match) {
        Alert alert = new Alert();
        alert.setAlertNumber(Ids.next("ALT"));
        alert.setType(AlertType.CUSTOMER_SCREENING);
        alert.setCustomer(customer);
        int score = (int) Math.round(match.score() * 100);
        alert.setScore(score);
        alert.setSeverity(Severity.CRITICAL);
        alert.setHits(List.of(new RuleHit("CUSTOMER_SANCTIONS_SCREENING", "Customer name screening", score,
                "Customer name \"" + customer.getFullName() + "\" matches listed party \"" + match.listedName()
                        + "\" (" + match.listSource() + (match.program() == null ? "" : ", " + match.program())
                        + ") with " + score + "% similarity.")));
        alert.setSummary("Possible sanctions match at onboarding: " + match.listedName());
        alerts.save(alert);
        notes.save(new AlertNote(alert, SYSTEM, "Alert generated by customer name screening.", true));
        events.publishEvent(new UrgentAlertRaised(alert.getId(), alert.getAlertNumber(), customer.getFullName(),
                alert.getSummary(), alert.getSeverity(), false));
        return alert;
    }

    // ---------------------------------------------------------------- queries

    @Transactional(readOnly = true)
    public PageDto<AlertSummaryDto> search(AlertStatus status, boolean openOnly, Severity severity,
                                           Long customerId, int page, int size) {
        PageRequest pr = PageRequest.of(page, Math.min(size, 100),
                Sort.by(Sort.Order.desc("createdAt")));
        return PageDto.of(alerts.search(status, openOnly, CustomerRiskService.OPEN_STATUSES, severity,
                customerId, pr), DtoMapper::toSummary);
    }

    @Transactional(readOnly = true)
    public AlertDetailDto detail(Long id) {
        Alert a = load(id);
        return new AlertDetailDto(
                DtoMapper.toSummary(a),
                a.getHits().stream().map(DtoMapper::toDto).toList(),
                a.getTransaction() == null ? null : DtoMapper.toDto(a.getTransaction()),
                DtoMapper.toDto(a.getCustomer()),
                notes.findByAlertIdOrderByCreatedAtAsc(id).stream().map(DtoMapper::toDto).toList(),
                sars.findByAlertId(id).map(DtoMapper::toDto).orElse(null));
    }

    @Transactional(readOnly = true)
    public List<SarDto> listSars() {
        return sars.findAllDetailed().stream().map(DtoMapper::toDto).toList();
    }

    // ---------------------------------------------------------------- workflow

    @Transactional
    public AlertDetailDto assign(Long id, AssignRequest req) {
        Alert a = loadOpen(id);
        String previous = a.getAssignedTo();
        a.setAssignedTo(req.analyst());
        if (a.getStatus() == AlertStatus.OPEN) {
            a.setStatus(AlertStatus.IN_REVIEW);
        }
        notes.save(new AlertNote(a, req.analyst(), previous == null
                ? "Assigned to " + req.analyst() + "; review started."
                : "Reassigned from " + previous + " to " + req.analyst() + ".", true));
        return detail(id);
    }

    @Transactional
    public NoteDto addNote(Long id, NoteRequest req) {
        Alert a = load(id);
        return DtoMapper.toDto(notes.save(new AlertNote(a, req.author(), req.text(), false)));
    }

    @Transactional
    public AlertDetailDto changeStatus(Long id, StatusChangeRequest req) {
        Alert a = loadOpen(id);
        AlertStatus target = req.status();
        if (target == AlertStatus.CLOSED_SAR_FILED) {
            throw new BusinessRuleException("Use the SAR filing action to close an alert with a SAR.");
        }
        if (target == AlertStatus.OPEN) {
            throw new BusinessRuleException("An alert cannot be moved back to OPEN.");
        }
        if (target == AlertStatus.CLOSED_FALSE_POSITIVE && (req.comment() == null || req.comment().isBlank())) {
            throw new BusinessRuleException("A rationale is required to close an alert as a false positive.");
        }
        AlertStatus from = a.getStatus();
        a.setStatus(target);
        if (a.getAssignedTo() == null) {
            a.setAssignedTo(req.analyst());
        }
        StringBuilder text = new StringBuilder("Status changed from " + from + " to " + target + ".");
        if (req.comment() != null && !req.comment().isBlank()) {
            text.append(" Rationale: ").append(req.comment().trim());
        }
        if (target.isClosed()) {
            a.setClosedAt(Instant.now());
            releaseIfBlocked(a, text);
        }
        notes.save(new AlertNote(a, req.analyst(), text.toString(), true));
        risk.recalculate(a.getCustomer());
        if (target == AlertStatus.ESCALATED && from != AlertStatus.ESCALATED) {
            events.publishEvent(new AlertEscalated(a.getId(), a.getAlertNumber(), a.getCustomer().getFullName(),
                    a.getSummary(), req.analyst(), req.comment()));
        }
        return detail(id);
    }

    @Transactional
    public AlertDetailDto fileSar(Long id, SarRequest req) {
        Alert a = loadOpen(id);
        SarReport sar = new SarReport();
        sar.setSarNumber(Ids.next("SAR"));
        sar.setAlert(a);
        sar.setCustomer(a.getCustomer());
        sar.setNarrative(req.narrative().trim());
        sar.setFiledBy(req.analyst());
        sars.save(sar);

        a.setStatus(AlertStatus.CLOSED_SAR_FILED);
        a.setClosedAt(Instant.now());
        if (a.getAssignedTo() == null) {
            a.setAssignedTo(req.analyst());
        }
        notes.save(new AlertNote(a, req.analyst(), "SAR " + sar.getSarNumber()
                + " filed and alert closed. Any held transaction remains blocked.", true));
        risk.recalculate(a.getCustomer());
        return detail(id);
    }

    /** A false positive on a held transaction releases it and posts it to the account. */
    private void releaseIfBlocked(Alert a, StringBuilder text) {
        Transaction tx = a.getTransaction();
        if (a.getStatus() != AlertStatus.CLOSED_FALSE_POSITIVE || tx == null
                || tx.getStatus() != TransactionStatus.BLOCKED) {
            return;
        }
        tx.setStatus(TransactionStatus.FLAGGED);
        Account account = tx.getAccount();
        account.setBalance(tx.getType().isInbound()
                ? account.getBalance().add(tx.getAmount())
                : account.getBalance().subtract(tx.getAmount()));
        text.append(" Held transaction ").append(tx.getReference()).append(" released and posted.");
    }

    private Alert load(Long id) {
        return alerts.findDetailed(id).orElseThrow(() -> new NotFoundException("Alert", id));
    }

    private Alert loadOpen(Long id) {
        Alert a = load(id);
        if (a.getStatus().isClosed()) {
            throw new BusinessRuleException("Alert " + a.getAlertNumber() + " is closed and can no longer be changed.");
        }
        return a;
    }
}
